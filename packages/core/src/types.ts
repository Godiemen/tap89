import type { LatLng } from './geo';

export type Role = 'customer' | 'driver' | 'store' | 'admin';

/** The signed-in user's session + their row in the role table.
 *  userId doubles as the row id in customers/drivers/stores. */
export interface Account {
  userId: string;
  role: Role;
  name: string;
  email: string;
  address?: string; // customer delivery address / store address
  pos?: { x: number; y: number };
  latLng?: LatLng; // real coordinates (geocoded address / GPS)
  approved?: boolean; // store: admin approved
  verified?: boolean; // driver: admin verified
  vehicle?: string;
  plate?: string;
}

export type OrderStatus =
  | 'placed' // sent to store, awaiting acceptance
  | 'accepted' // store accepted
  | 'preparing'
  | 'ready' // waiting for driver pickup
  | 'driver_assigned'
  | 'picked_up'
  | 'en_route'
  | 'delivered'
  | 'rejected'
  | 'cancelled';

export type Category = 'beer' | 'wine' | 'spirits' | 'mixers' | 'snacks' | 'extras';

export interface Product {
  id: string;
  storeId: string;
  name: string;
  brand: string;
  category: Category;
  size: string; // e.g. "750ml", "6-pack"
  abv?: number;
  price: number;
  image: string; // emoji used as visual placeholder
  description: string;
  tags: string[];
  available: boolean;
  popular?: boolean;
}

export interface Store {
  id: string;
  name: string;
  emoji: string;
  categories: Category[];
  rating: number;
  ratingCount: number;
  deliveryTimeMin: number;
  deliveryTimeMax: number;
  deliveryFee: number;
  minOrder: number;
  distanceKm: number;
  address: string;
  phone: string;
  open: boolean;
  paused: boolean;
  pausedUntil?: number; // epoch ms — timed pause auto-resumes via sweep
  openHours?: Record<string, [string, string]>; // e.g. { mon: ["09:00","23:00"] } — missing day = closed
  prepTimeMin: number;
  approved: boolean;
  featured?: boolean;
  promo?: string;
  pos: { x: number; y: number }; // position on the simulated city map (0-100)
  latLng?: LatLng; // real coordinates — wins over pos when present
  busyLevel: 0 | 1 | 2; // affects prep time + surge
}

export interface Driver {
  id: string;
  name: string;
  vehicle: string;
  plate: string;
  phone?: string;
  rating: number;
  trips: number;
  online: boolean;
  verified: boolean;
  pos: { x: number; y: number };
  latLng?: LatLng;
  avatarColor: string;
}

export interface Customer {
  id: string;
  name: string;
  email: string;
  phone: string;
  ageVerified: boolean;
  latLng?: LatLng; // delivery pin — geocoded address or map pick
  orders: number;
  spent: number;
  joined: string;
  status: 'active' | 'suspended';
}

export interface CartItem {
  productId: string;
  qty: number;
}

export interface OrderItem {
  productId: string;
  name: string;
  price: number;
  qty: number;
  emoji: string;
}

export interface StatusEvent {
  status: OrderStatus;
  at: number; // timestamp
}

export interface Order {
  id: string;
  customerId: string;
  customerName: string;
  customerAddress: string;
  customerPos: { x: number; y: number };
  customerLatLng?: LatLng; // real drop-off (snapshot at placement)
  storeId: string;
  storeName: string;
  storePos: { x: number; y: number };
  storeLatLng?: LatLng; // real pickup (snapshot at placement)
  driverId?: string;
  driverName?: string;
  items: OrderItem[];
  subtotal: number;
  deliveryFee: number;
  serviceFee: number;
  surgeFee: number;
  discount: number;
  tip: number;
  total: number;
  promoCode?: string;
  status: OrderStatus;
  placedAt: number;
  etaMinutes: number;
  timeline: StatusEvent[];
  driverPos?: { x: number; y: number };
  driverLatLng?: LatLng; // live courier GPS fix
  driverProgress?: number; // 0-1 along route
  rating?: number;
  cancelReason?: string; // set by timeout sweeps / system cancellations
  flagged?: boolean; // stuck delivery — needs admin review
  flagReason?: string;
  instructions?: string; // customer's note to the store (allergies, handoff)
  isLive?: boolean; // generated by the prototype session
}

export interface Promo {
  code: string;
  description: string;
  type: 'percent' | 'flat' | 'free_delivery';
  value: number; // percent or flat currency
  minSubtotal: number;
  active: boolean;
  uses: number;
}

export interface DeliveryRequest {
  id: string;
  orderId: string;
  storeName: string;
  storeAddress: string;
  storePos: { x: number; y: number };
  customerAddress: string;
  customerPos: { x: number; y: number };
  distanceKm: number;
  payout: number;
  items: number;
  expiresIn: number; // seconds countdown
  surge: number; // multiplier
}

export interface Trip {
  id: string;
  orderId: string;
  storeName: string;
  customerAddress: string;
  distanceKm: number;
  payout: number;
  tip: number;
  at: number;
  rating?: number;
}

export interface AppNotification {
  id: string;
  title: string;
  body: string;
  at: number;
  read: boolean;
  kind: 'order' | 'promo' | 'system';
}
